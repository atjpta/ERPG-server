/** `userPlayer_index`, `EQUIP_ITEM`, `equip-item` → `UserPlayerIndex`, `EquipItem`, `EquipItem`. */
export function pascal(name: string): string {
    return name
        .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
        .split(/[^A-Za-z0-9]+/)
        .filter(Boolean)
        .map((part) => part[0].toUpperCase() + part.slice(1).toLowerCase())
        .join("");
}

/** Giữ nguyên hoa/thường phần còn lại: `userPlayerIndex` → `UserPlayerIndex`. */
export function upperFirst(name: string): string {
    return name ? name[0].toUpperCase() + name.slice(1) : name;
}

export function lowerFirst(name: string): string {
    return name ? name[0].toLowerCase() + name.slice(1) : name;
}

/** Tên field / tham số C# (thêm `@` nếu trùng từ khoá). */
export function identifier(name: string): string {
    const clean = name.replace(/[^A-Za-z0-9_]/g, "_");
    const safe = /^[0-9]/.test(clean) ? `_${clean}` : clean;
    return CSHARP_KEYWORDS.has(safe) ? `@${safe}` : safe;
}

export function xmlEscape(text: string): string {
    return text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/** JSDoc / chú thích tiếng Việt có thể dùng backtick: đổi `x` thành <c>x</c> để XML doc đẹp. */
export function docText(text: string): string {
    return xmlEscape(text.trim())
        .replace(/`([^`]+)`/g, "<c>$1</c>")
        .replace(/\s*\n\s*/g, " ");
}

/** Dòng `///` XML doc, thụt `indent` khoảng trắng. */
export function summaryLines(text: string | undefined, indent: string): string[] {
    if (!text) return [];
    return [`${indent}/// <summary>${docText(text)}</summary>`];
}

