/**
 * Xuất skill đang bật trong DB ra `<outputDir>/skills.json` cho client — client không giữ bản copy
 * tay nào. Mọi giá trị đã quy đổi sẵn theo đúng cách server dùng (tick mô phỏng, thời lượng đòn,
 * hệ số damage), nên client chỉ việc đọc, không tự tính lại.
 *
 * `outputDir` là thư mục `Resources/Config` của project Unity, truyền từ script trong package.json
 * (`seed`, `config:export`); thư mục cha không tồn tại (vd. chạy seed trên server deploy) thì bỏ qua.
 */
export async function exportClientConfig(outputDir: string): Promise<void> {
    const directory = resolve(outputDir);
    if (!existsSync(dirname(directory))) {
        console.info(`⏭️  [ClientConfig] ${directory} not found — skipped`);
        return;
    }

    const skills = await SkillRepo.findEnabled();
    const config = {
        comment:
            "Generated by ERPG-server (yarn config:export) from the skills table. Do not edit.",
        tickRate: WORLD_TICK_RATE,
        skills: skills.map(toClientSkill),
    };

    mkdirSync(directory, { recursive: true });
    const file = join(directory, "skills.json");
    writeFileSync(file, `${JSON.stringify(config, null, 4)}\n`, "utf8");
    console.info(`✅ [ClientConfig] ${skills.length} skills -> ${file}`);

    await exportContentConfig(directory);
    await exportMonsterCodes(directory);
    await exportClassCodes(directory);
    exportInteractableCodes(directory);
    exportMapCodes(directory);
    exportMapMarkers(directory);
}

/**
 * `map-markers.json`: marker mỗi map mà Unity phải đặt vị trí (spawn point, nhóm quái, NPC, vật thể, chamber
 * dungeon) — config nằm ở server, Unity chỉ chỉnh vị trí rồi export `<code>.map.json`.
 */
function exportMapMarkers(directory: string): void {
    const maps = loadMapDefinitions().map(mapMarkerList);
    writeFileSync(
        join(directory, "map-markers.json"),
        `${JSON.stringify({ comment: "Generated by ERPG-server (yarn config:export). Do not edit.", maps }, null, 4)}
`,
        "utf8"
    );
    console.info(`✅ [ClientConfig] ${maps.length} map marker lists`);
}

/** `map-codes.json`: code mọi map (registry + file Unity) — Unity Editor dùng cho dropdown của bảng prefab map. */
function exportMapCodes(directory: string): void {
    const codes = loadMapDefinitions()
        .map((map) => map.code)
        .sort((a, b) => a.localeCompare(b));
    const config = {
        comment: "Generated by ERPG-server (yarn config:export). Do not edit.",
        maps: codes.map((code) => ({ code })),
    };
    writeFileSync(
        join(directory, "map-codes.json"),
        `${JSON.stringify(config, null, 4)}
`,
        "utf8"
    );
    console.info(`✅ [ClientConfig] ${codes.length} map codes`);
}

/** `interactable-codes.json`: code diện mạo của vật thể tương tác — Unity Editor dùng cho dropdown của marker và bảng prefab. */
