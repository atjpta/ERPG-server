/**
 * Xuất skill đang bật trong DB ra `<outputDir>/skills.json` cho client — client không giữ bản copy
 * tay nào. Mọi giá trị đã quy đổi sẵn theo đúng cách server dùng (tick mô phỏng, thời lượng đòn,
 * hệ số damage), nên client chỉ việc đọc, không tự tính lại.
 *
 * `outputDir` là thư mục `Resources/Config` của project Unity, truyền từ script trong package.json
 * (`seed`, `config:export`); thư mục cha không tồn tại (vd. chạy seed trên server deploy) thì bỏ qua.
 * Chỉ `skills.json` nằm ở đây vì client đọc lúc chạy. Dữ liệu chỉ Unity Editor dùng (danh sách code cho dropdown,
 * content, locale-keys, map-markers) ghi vào `Assets/ERPG/ServerData` (cùng cấp `Resources`) để không vào build.
 */
export async function exportClientConfig(outputDir: string): Promise<void> {
    const directory = resolve(outputDir);
    if (!existsSync(dirname(directory))) {
        console.info(`⏭️  [ClientConfig] ${directory} not found — skipped`);
        return;
    }

    const skills = await SkillRepo.findEnabled();
    const config = {
        comment:
            "Generated by ERPG-server (yarn config:export) from the skills table and master data player_target_config. Do not edit.",
        tickRate: WORLD_TICK_RATE,
        targeting: await loadTargetingConfig(),
        skills: skills.map(toClientSkill),
    };

    mkdirSync(directory, { recursive: true });
    const file = join(directory, "skills.json");
    writeFileSync(file, `${JSON.stringify(config, null, 4)}\n`, "utf8");
    console.info(`✅ [ClientConfig] ${skills.length} skills -> ${file}`);

    const dataDirectory = resolve(directory, "..", "..", "ServerData");
    mkdirSync(dataDirectory, { recursive: true });
    await exportContentConfig(dataDirectory);
    await exportMonsterCodes(dataDirectory);
    await exportClassCodes(dataDirectory);
    exportInteractableCodes(dataDirectory);
    exportMapCodes(dataDirectory);
    exportGateCodes(dataDirectory);
    exportMapMarkers(dataDirectory);
    await exportItemCodes(dataDirectory);
    exportCurrencyCodes(dataDirectory);
}

/**
 * Master data `player_target_config` cho client (cùng công thức chọn / quay mặt target với server): mỗi class đã
 * gộp sẵn với `default`, client chỉ tra `classes[classCode] ?? default`.
 */
async function loadTargetingConfig() {
    const row = await MasterDataRepo.findByKey({ key: MasterDataKey.PLAYER_TARGET_CONFIG });
    const config = row
        ? PlayerTargetConfigSchema.parse(row.value)
        : PlayerTargetConfigSchema.parse(DEFAULT_PLAYER_TARGET_CONFIG);
    return {
        keepTargetRange: config.keepTargetRange,
        approachDeadzone: config.approachDeadzone,
        default: config.default,
        classes: Object.fromEntries(
            Object.keys(config.classes).map((code) => [code, resolvePlayerTargetRule(config, code)])
        ),
        autoBattle: config.autoBattle,
    };
}

