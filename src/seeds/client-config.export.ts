import { exportCatalogCodes } from "@/seeds/catalog-codes.export.js";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { DialogueRepo } from "@/modules/dialogues/repositories/dialogue.repository.js";
import { MasterDataKey } from "@/modules/master-data/enums/master-data.enum.js";
import { MasterDataRepo } from "@/modules/master-data/repositories/master-data.repository.js";
import {
    DEFAULT_PLAYER_TARGET_CONFIG,
    PlayerTargetConfigSchema,
} from "@/modules/master-data/schemas/player-target-config.schema.js";
import { loadMapDefinitions } from "@/modules/maps/seeds/game-map.seed.js";
import { mapMarkerList } from "@/modules/maps/seeds/map-build.seed-util.js";
import { NpcRepo } from "@/modules/npcs/repositories/npc.repository.js";
import { QuestRepo } from "@/modules/quests/repositories/quest.repository.js";
import { collectLocaleKeys } from "@/modules/quests/seeds/locale-keys.seed-util.js";
import { SkillRepo } from "@/modules/skills/repositories/skill.repository.js";
import { buildClientSkillConfig } from "@/rooms/world/combat/utils/skill-config.world.util.js";

/** Exports offline authoring data to ServerData. Runtime clients request skill config from their world room. */
export async function exportClientConfig(outputDir: string): Promise<void> {
    const directory = resolve(outputDir);
    if (!existsSync(dirname(directory))) {
        console.info(`⏭️  [ClientConfig] ${directory} not found — skipped`);
        return;
    }

    exportCatalogCodes(resolve(directory, "..", "..", "..", ".."));

    const skills = await SkillRepo.findEnabled();
    const config = buildClientSkillConfig(skills, await loadTargetingConfig());
    const dataDirectory = resolve(directory, "..", "..", "ServerData");
    mkdirSync(dataDirectory, { recursive: true });
    const file = join(dataDirectory, "skills.json");
    writeFileSync(file, `${JSON.stringify(config, null, 4)}\n`, "utf8");
    console.info(`ClientConfig: ${skills.length} editor skills -> ${file}`);

    await exportContentConfig(dataDirectory);
    exportMapMarkers(dataDirectory);
}

/**
 * Master data `player_target_config` cho client (cùng công thức chọn / quay mặt target với server): mỗi class đã
 * gộp sẵn với `default`, client chỉ tra `classes[classCode] ?? default`.
 */
async function loadTargetingConfig() {
    const row = await MasterDataRepo.findByKey({ key: MasterDataKey.PLAYER_TARGET_CONFIG });
    const config = row
        ? PlayerTargetConfigSchema.parse(row.value)
        : PlayerTargetConfigSchema.parse(DEFAULT_PLAYER_TARGET_CONFIG);
    return config;
}

/**
 * `map-markers.json`: marker mỗi map mà Unity phải đặt vị trí (spawn point, nhóm quái, NPC, vật thể, chamber
 * dungeon) — config nằm ở server, Unity chỉ chỉnh vị trí rồi export `<code>.map.json`.
 */
function exportMapMarkers(directory: string): void {
    const maps = loadMapDefinitions().map(mapMarkerList);
    writeFileSync(
        join(directory, "map-markers.json"),
        `${JSON.stringify({ comment: "Generated by ERPG-server (yarn config:export). Do not edit.", maps }, null, 4)}
`,
        "utf8"
    );
    console.info(`✅ [ClientConfig] ${maps.length} map marker lists`);
}

/**
 * `content.json` (NPC, thoại, quest) + `locale-keys.json` (mọi key cần dịch). Layout map không xuất ở đây:
 * map do Unity export ra file `.map.json` nên client đã có sẵn.
 */
async function exportContentConfig(directory: string): Promise<void> {
    const [npcs, dialogues, quests] = await Promise.all([
        NpcRepo.findEnabled(),
        DialogueRepo.findEnabled(),
        QuestRepo.findEnabled(),
    ]);
    const content = {
        comment: "Generated by ERPG-server (yarn config:export). Do not edit.",
        npcs: npcs.map(({ code, colliderWidth, colliderHeight, interactRadius, functions }) => ({
            code,
            colliderWidth,
            colliderHeight,
            interactRadius,
            functions,
        })),
        dialogues: dialogues.map(({ code, nodes }) => ({ code, nodes })),
        quests: quests.map((quest) => ({
            code: quest.code,
            category: quest.category,
            sortOrder: quest.sortOrder,
            chapter: quest.chapter,
            unlockFeatures: quest.unlockFeatures,
            requiredLevel: quest.requiredLevel,
            giverNpcCode: quest.giverNpcCode,
            turnInNpcCode: quest.turnInNpcCode,
            repeat: quest.repeat,
            objectives: quest.objectives,
            rewards: quest.rewards,
        })),
    };
    const keys = collectLocaleKeys({
        maps: loadMapDefinitions(),
        npcs,
        dialogues,
        quests,
    });
    writeFileSync(
        join(directory, "content.json"),
        `${JSON.stringify(content, null, 4)}
`,
        "utf8"
    );
    writeFileSync(
        join(directory, "locale-keys.json"),
        `${JSON.stringify(keys, null, 4)}
`,
        "utf8"
    );
    console.info(
        `✅ [ClientConfig] ${npcs.length} npcs, ${dialogues.length} dialogues, ${quests.length} quests, ${keys.length} locale keys`
    );
}
