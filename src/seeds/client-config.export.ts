/**
 * Xuất skill đang bật trong DB ra `<outputDir>/skills.json` cho client — client không giữ bản copy
 * tay nào. Mọi giá trị đã quy đổi sẵn theo đúng cách server dùng (tick mô phỏng, thời lượng đòn,
 * hệ số damage), nên client chỉ việc đọc, không tự tính lại.
 *
 * `outputDir` là thư mục `Resources/Config` của project Unity, truyền từ script trong package.json
 * (`seed`, `config:export`); thư mục cha không tồn tại (vd. chạy seed trên server deploy) thì bỏ qua.
 * Chỉ `skills.json` nằm ở đây vì client đọc lúc chạy. Dữ liệu chỉ Unity Editor dùng (danh sách code cho dropdown,
 * content, locale-keys, map-markers) ghi vào `Assets/ERPG/ServerData` (cùng cấp `Resources`) để không vào build.
 */
export async function exportClientConfig(outputDir: string): Promise<void> {
    const directory = resolve(outputDir);
    if (!existsSync(dirname(directory))) {
        console.info(`⏭️  [ClientConfig] ${directory} not found — skipped`);
        return;
    }

    const skills = await SkillRepo.findEnabled();
    const config = {
        comment:
            "Generated by ERPG-server (yarn config:export) from the skills table and master data player_target_config. Do not edit.",
        tickRate: WORLD_TICK_RATE,
        targeting: await loadTargetingConfig(),
        skills: skills.map(toClientSkill),
    };

    mkdirSync(directory, { recursive: true });
    const file = join(directory, "skills.json");
    writeFileSync(file, `${JSON.stringify(config, null, 4)}\n`, "utf8");
    console.info(`✅ [ClientConfig] ${skills.length} skills -> ${file}`);

    const dataDirectory = resolve(directory, "..", "..", "ServerData");
    mkdirSync(dataDirectory, { recursive: true });
    await exportContentConfig(dataDirectory);
    await exportCodes(dataDirectory, skills);
    exportMapMarkers(dataDirectory);
}

/**
 * Master data `player_target_config` cho client (cùng công thức chọn / quay mặt target với server): mỗi class đã
 * gộp sẵn với `default`, client chỉ tra `classes[classCode] ?? default`.
 */
async function loadTargetingConfig() {
    const row = await MasterDataRepo.findByKey({ key: MasterDataKey.PLAYER_TARGET_CONFIG });
    const config = row
        ? PlayerTargetConfigSchema.parse(row.value)
        : PlayerTargetConfigSchema.parse(DEFAULT_PLAYER_TARGET_CONFIG);
    return {
        keepTargetRange: config.keepTargetRange,
        approachDeadzone: config.approachDeadzone,
        default: config.default,
        classes: Object.fromEntries(
            Object.keys(config.classes).map((code) => [code, resolvePlayerTargetRule(config, code)])
        ),
        autoBattle: config.autoBattle,
    };
}

/**
 * `codes.json`: mọi danh sách code server định nghĩa, gộp một file — nguồn duy nhất cho dropdown `[ServerCode]` của Unity Editor
 * (mọi chuỗi code trong Unity đều chọn từ đây, không gõ tay). Chỉ có `code`; chi tiết nằm ở `content.json` / `map-markers.json` / `skills.json`.
 */
async function exportCodes(directory: string, skills: Skill[]): Promise<void> {
    const [classes, monsters, npcs, dialogues, quests, items] = await Promise.all([
        ClassRepo.findEnabled(),
        MonsterRepo.findAll(),
        NpcRepo.findEnabled(),
        DialogueRepo.findEnabled(),
        QuestRepo.findEnabled(),
        ItemRepo.findEnabled(),
    ]);
    const list = (codes: Iterable<string>) =>
        [...codes].sort((a, b) => a.localeCompare(b)).map((code) => ({ code }));
    const codes = {
        comment: "Generated by ERPG-server (yarn config:export). Do not edit.",
        classes: list(classes.map((row) => row.code)),
        monsters: list(monsters.map((row) => row.code)),
        npcs: list(npcs.map((row) => row.code)),
        dialogues: list(dialogues.map((row) => row.code)),
        quests: list(quests.map((row) => row.code)),
        items: list(items.map((row) => row.code)),
        currencies: list(Object.values(CurrencyCode)),
        gates: list(Object.values(GateCode)),
        interactables: list(Object.values(InteractableCode)),
        maps: list(loadMapDefinitions().map((map) => map.code)),
        skills: list(skills.map((row) => row.code)),
    };
    writeFileSync(
        join(directory, "codes.json"),
        `${JSON.stringify(codes, null, 4)}
`,
        "utf8"
    );
    console.info(
        `✅ [ClientConfig] codes: ${Object.entries(codes)
            .filter(([, value]) => Array.isArray(value))
            .map(([key, value]) => `${(value as unknown[]).length} ${key}`)
            .join(", ")}`
    );
}

/**
 * `map-markers.json`: marker mỗi map mà Unity phải đặt vị trí (spawn point, nhóm quái, NPC, vật thể, chamber
 * dungeon) — config nằm ở server, Unity chỉ chỉnh vị trí rồi export `<code>.map.json`.
 */
function exportMapMarkers(directory: string): void {
    const maps = loadMapDefinitions().map(mapMarkerList);
    writeFileSync(
        join(directory, "map-markers.json"),
        `${JSON.stringify({ comment: "Generated by ERPG-server (yarn config:export). Do not edit.", maps }, null, 4)}
`,
        "utf8"
    );
    console.info(`✅ [ClientConfig] ${maps.length} map marker lists`);
}

/**
 * `content.json` (NPC, thoại, quest) + `locale-keys.json` (mọi key cần dịch). Layout map không xuất ở đây:
 * map do Unity export ra file `.map.json` nên client đã có sẵn.
 */
async function exportContentConfig(directory: string): Promise<void> {
    const [npcs, dialogues, quests] = await Promise.all([
        NpcRepo.findEnabled(),
        DialogueRepo.findEnabled(),
        QuestRepo.findEnabled(),
    ]);
    const content = {
        comment: "Generated by ERPG-server (yarn config:export). Do not edit.",
        npcs: npcs.map(({ code, colliderWidth, colliderHeight, interactRadius, functions }) => ({
            code,
            colliderWidth,
            colliderHeight,
            interactRadius,
            functions,
        })),
        dialogues: dialogues.map(({ code, nodes }) => ({ code, nodes })),
        quests: quests.map((quest) => ({
            code: quest.code,
            category: quest.category,
            sortOrder: quest.sortOrder,
            chapter: quest.chapter,
            unlockFeatures: quest.unlockFeatures,
            requiredLevel: quest.requiredLevel,
            giverNpcCode: quest.giverNpcCode,
            turnInNpcCode: quest.turnInNpcCode,
            repeat: quest.repeat,
            objectives: quest.objectives,
            rewards: quest.rewards,
        })),
    };
    const keys = collectLocaleKeys({
        maps: loadMapDefinitions(),
        npcs,
        dialogues,
        quests,
    });
    writeFileSync(
        join(directory, "content.json"),
        `${JSON.stringify(content, null, 4)}
`,
        "utf8"
    );
    writeFileSync(
        join(directory, "locale-keys.json"),
        `${JSON.stringify(keys, null, 4)}
`,
        "utf8"
    );
    console.info(
        `✅ [ClientConfig] ${npcs.length} npcs, ${dialogues.length} dialogues, ${quests.length} quests, ${keys.length} locale keys`
    );
}

function toClientSkill(skill: Skill) {
    return {
        id: skill.id,
        code: skill.code,
        skillType: skill.skillType,
        castRange: skill.castRange,
        cooldownMs: skill.cooldownMs,
        manaCost: skill.manaCost,
        /** Thuộc combo đánh thường (theo thứ tự trong `skills` của player/monster). */
        basicAttack: skill.basicAttack,
        /** Chỉ skill lướt tới mục tiêu (`isChargeSkill`): tốc độ, thời gian dư, quãng lướt không mục tiêu — đã điền mặc định. */
        charge: isChargeSkill(skill)
            ? {
                  ...getChargeConfig(skill),
                  freeDistance: getChargeConfig(skill).freeDistance ?? skill.castRange,
              }
            : null,
        /** Số tick chờ từ lúc bấm đến lúc anim + hit event bắt đầu (`castTimeMs`; 0 = ngay). */
        castTicks: getSkillCastTicks(skill, WORLD_TICK_RATE),
        /** Số tick mô phỏng của cả đòn (chờ + anim, khoá di chuyển) — giống PlayerAttackChain. */
        durationTicks: getSkillDurationTicks(skill, WORLD_TICK_RATE),
        hitEvents: sortSkillHitEvents(skill.skillHitEvents).map((event) => {
            const damageEffects = event.effects.filter(
                (effect) => effect.effectType === SkillEffectType.DAMAGE
            );
            return {
                /** Tick mô phỏng (WORLD_TICK_RATE) tính từ lúc bắt đầu đòn. */
                triggerTicks: skillEventTicks(event.triggerTicks, WORLD_TICK_RATE),
                shape: event.shape,
                range: event.range,
                width: event.width,
                height: event.height,
                radius: event.radius,
                angle: event.angle,
                /** Vùng đánh xoay theo hướng ngắm (về phía target đang chọn) thay vì chỉ trái / phải. */
                aimed: event.aimed ?? false,
                /** Vùng đánh / chỗ đạn và vùng bắt đầu so với người đánh (ô): về trước theo hướng mặt hoặc ngắm, và lên trên. */
                offsetX: event.offsetX ?? 0,
                offsetY: event.offsetY ?? 0,
                /** Hit cùng nhóm = một hit vẽ từng frame (-1 = hit riêng): mỗi mục tiêu chỉ trúng frame đầu tiên chạm nó. */
                hitGroup: event.hitGroup ?? -1,
                /** Damage gốc để client predict: damageBase + attack × damageAttackScaling (server tính đủ qua `calculateDamage`). */
                damageBase: damageEffects.reduce((total, effect) => total + effect.baseValue, 0),
                damageAttackScaling: damageEffects
                    .filter((effect) => effect.scalingType === DamageScalingType.ATTACK)
                    .reduce((total, effect) => total + effect.scalingValue, 0),
                /** HITBOX / PROJECTILE / AREA — xem SkillDeliveryWorldService. */
                delivery: event.delivery ?? HitDelivery.HITBOX,
                projectile: event.projectile
                    ? {
                          speed: event.projectile.speed,
                          maxDistance: event.projectile.maxDistance,
                          radius: event.projectile.radius,
                          hitBehavior: event.projectile.hitBehavior,
                          maxHits: event.projectile.maxHits,
                      }
                    : null,
                area: event.area
                    ? {
                          /** Tick mô phỏng từ lúc đặt vùng tới lúc gây damage (0 = ngay). */
                          delayTicks:
                              event.area.delayMs > 0
                                  ? millisecondsToTicks(event.area.delayMs, WORLD_TICK_RATE)
                                  : 0,
                          untargetedDistance: event.area.untargetedDistance,
                          /** Vùng kéo dài: số lần gây damage và chu kỳ giữa hai lần (tick); 1 / 0 = chỉ một lần. */
                          ...(event.area.durationMs
                              ? {
                                    pulseTicks: millisecondsToTicks(
                                        event.area.tickMs ?? 1000,
                                        WORLD_TICK_RATE
                                    ),
                                    pulses:
                                        Math.floor(
                                            Math.max(
                                                0,
                                                millisecondsToTicks(
                                                    event.area.durationMs,
                                                    WORLD_TICK_RATE
                                                ) -
                                                    (event.area.delayMs > 0
                                                        ? millisecondsToTicks(
                                                              event.area.delayMs,
                                                              WORLD_TICK_RATE
                                                          )
                                                        : 0)
                                            ) /
                                                millisecondsToTicks(
                                                    event.area.tickMs ?? 1000,
                                                    WORLD_TICK_RATE
                                                )
                                        ) + 1,
                                }
                              : { pulseTicks: 0, pulses: 1 }),
                      }
                    : null,
                /** Vùng buff (AURA): thời gian và bán kính theo level, để client tính hồi chiêu và phóng prefab. */
                aura: event.aura
                    ? {
                          durationMs: event.aura.durationMs,
                          durationMsPerLevel: event.aura.durationMsPerLevel,
                          radiusX: event.aura.radiusX,
                          radiusY: event.aura.radiusY,
                          radiusScalePerLevel: event.aura.radiusScalePerLevel,
                      }
                    : null,
                /** Hồi đồng đội quanh người dùng (ALLIES): vùng elip và lượng hồi. */
                allies: event.allies
                    ? {
                          radiusX: event.allies.radiusX,
                          radiusY: event.allies.radiusY,
                          healBase: event.allies.healBase,
                          healScaling: event.allies.healScaling,
                      }
                    : null,
            };
        }),
    };
}
