import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { CATALOG_CODES } from "@/seeds/catalog-codes.constant.js";
import { checkCatalogCodes } from "@/seeds/catalog-codes.check.js";

const CATALOG_CODE_NAMES: Record<keyof typeof CATALOG_CODES, string> = {
    gameServers: "GameServerCode",
    classes: "ClassCode",
    dialogues: "DialogueCode",
    items: "ItemCode",
    maps: "MapCode",
    monsters: "MonsterCode",
    npcs: "NpcCode",
    quests: "QuestCode",
    skills: "SkillCode",
    currencies: "CurrencyCode",
    gates: "GateCode",
    interactables: "InteractableCode",
};

/** Offline sync: no database or running Unity Editor required. */
export function exportCatalogCodes(unityRoot: string): void {
    checkCatalogCodes(false);
    const root = resolve(unityRoot);
    const dataDirectory = join(root, "Assets/ERPG/ServerData");
    mkdirSync(dataDirectory, { recursive: true });
    const lists = Object.fromEntries(
        Object.entries(CATALOG_CODES).map(([kind, codes]) => [
            kind,
            Object.values(codes)
                .sort()
                .map((code) => ({ code })),
        ])
    );
    writeFileSync(
        join(dataDirectory, "codes.json"),
        `${JSON.stringify({ comment: "Generated by ERPG-server (yarn codes:generate). Do not edit.", ...lists }, null, 4)}\n`
    );
    exportCatalogCodeSchemas(join(root, "Assets/ERPG/Scripts/Schema"));
    console.info(`[CatalogCodes] Synced ${Object.keys(lists).length} code lists -> ${root}`);
}

export function exportCatalogCodeSchemas(schemaDirectory: string): void {
    checkCatalogCodes(false);
    mkdirSync(schemaDirectory, { recursive: true });
    for (const [kind, codes] of Object.entries(CATALOG_CODES)) {
        const name = CATALOG_CODE_NAMES[kind as keyof typeof CATALOG_CODES];
        const members = Object.entries(codes);
        // Match Colyseus string-enum output: wire values stay strings, available through named constants.
        const source = `// Generated by ERPG-server (yarn codes:generate). Do not edit.\nnamespace ERPG.Schema\n{\n    public struct ${name}\n    {\n${members.map(([key, value]) => `        public const string ${key} = ${JSON.stringify(value)};`).join("\n")}\n        public static readonly string[] Values = { ${members.map(([key]) => key).join(", ")} };\n    }\n}\n`;
        writeFileSync(join(schemaDirectory, `${name}.cs`), source);
    }
}
